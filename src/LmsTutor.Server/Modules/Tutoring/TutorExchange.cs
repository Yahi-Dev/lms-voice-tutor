using System.Text.Json;
using LmsTutor.Server.Modules.Catalog;
using LmsTutor.Server.Modules.Identity;
using Microsoft.EntityFrameworkCore;
using Microsoft.EntityFrameworkCore.ChangeTracking;
using Microsoft.EntityFrameworkCore.Metadata.Builders;

namespace LmsTutor.Server.Modules.Tutoring;

public enum QuestionInputMode
{
    Text,
    Voice,
}

/// <summary>One question and its answer, owned by a student within a lesson.</summary>
public sealed class TutorExchange
{
    public Guid Id { get; init; } = Guid.CreateVersion7();
    public Guid UserId { get; init; }
    public Guid LessonId { get; init; }

    /// <summary>Generated by the client and reused on retries, so a retried request never creates a duplicate.</summary>
    public Guid ClientMessageId { get; init; }

    public required string Question { get; init; }
    public QuestionInputMode InputMode { get; init; }
    public TutorReplyStatus Status { get; init; }
    public required string Answer { get; init; }
    public List<string> CitedSectionKeys { get; init; } = [];
    public required string Model { get; init; }
    public int? PromptTokens { get; init; }
    public int? CompletionTokens { get; init; }
    public int LatencyMilliseconds { get; init; }
    public DateTime CreatedAt { get; init; }
}

internal sealed class TutorExchangeConfiguration : IEntityTypeConfiguration<TutorExchange>
{
    public void Configure(EntityTypeBuilder<TutorExchange> builder)
    {
        builder.Property(e => e.Question).HasMaxLength(1000);
        builder.Property(e => e.Answer).HasMaxLength(4000);
        builder.Property(e => e.Model).HasMaxLength(100);
        builder.Property(e => e.InputMode).HasConversion<string>().HasMaxLength(10);
        builder.Property(e => e.Status).HasConversion<string>().HasMaxLength(30);

        builder.Property(e => e.CitedSectionKeys)
            .HasConversion(
                keys => JsonSerializer.Serialize(keys, JsonSerializerOptions.Default),
                json => JsonSerializer.Deserialize<List<string>>(json, JsonSerializerOptions.Default) ?? new List<string>(),
                new ValueComparer<List<string>>(
                    (left, right) => left!.SequenceEqual(right!),
                    keys => keys.Aggregate(0, (hash, key) => HashCode.Combine(hash, key.GetHashCode(StringComparison.Ordinal))),
                    keys => keys.ToList()))
            .HasMaxLength(500);

        builder.HasIndex(e => new { e.UserId, e.LessonId, e.CreatedAt });
        builder.HasIndex(e => new { e.UserId, e.ClientMessageId }).IsUnique();

        builder.HasOne<AppUser>().WithMany().HasForeignKey(e => e.UserId).OnDelete(DeleteBehavior.Cascade);
        builder.HasOne<Lesson>().WithMany().HasForeignKey(e => e.LessonId).OnDelete(DeleteBehavior.Cascade);
    }
}
